-- Esquema inicial de Espacia (versión 1.12.0).
-- Equivale a lo que Hibernate creaba con ddl-auto=update. En una base que ya existía antes de Flyway
-- este script no se ejecuta: Flyway la marca como versión 1 (baseline) y aplica solo las siguientes.

CREATE TABLE users (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre                  VARCHAR(255) NOT NULL,
    email                   VARCHAR(255) NOT NULL,
    password                VARCHAR(255) NOT NULL,
    rol                     VARCHAR(255) NOT NULL,
    activo                  BOOLEAN DEFAULT TRUE NOT NULL,
    creado_en               TIMESTAMP(6) NOT NULL,
    privacidad_aceptada_en  TIMESTAMP(6),
    privacidad_version      VARCHAR(20),
    email_verificado        BOOLEAN,
    email_verificado_en     TIMESTAMP(6),
    verificacion_token_hash VARCHAR(64),
    verificacion_expira_en  TIMESTAMP(6),
    password_cambiada_en    TIMESTAMP(6) WITH TIME ZONE,
    CONSTRAINT users_email_key UNIQUE (email),
    CONSTRAINT users_rol_check CHECK (rol IN ('ROLE_ESTUDIANTE', 'ROLE_FUNCIONARIO', 'ROLE_ADMIN'))
);

CREATE TABLE spaces (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre       VARCHAR(255) NOT NULL,
    descripcion  TEXT,
    tipo         VARCHAR(255) NOT NULL,
    capacidad    INTEGER,
    estado       VARCHAR(255) NOT NULL,
    ubicacion    VARCHAR(255),
    equipamiento TEXT
);

CREATE TABLE reservations (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id              BIGINT NOT NULL,
    space_id             BIGINT NOT NULL,
    fecha                DATE NOT NULL,
    hora_inicio          TIME(0) NOT NULL,
    hora_fin             TIME(0) NOT NULL,
    estado               VARCHAR(255) NOT NULL,
    motivo               VARCHAR(500),
    recordatorio_enviado BOOLEAN DEFAULT FALSE NOT NULL,
    creada_en            TIMESTAMP(6) NOT NULL,
    CONSTRAINT fk_reservations_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT fk_reservations_space FOREIGN KEY (space_id) REFERENCES spaces (id),
    CONSTRAINT reservations_estado_check CHECK (estado IN
        ('PENDIENTE', 'CONFIRMADA', 'RECHAZADA', 'EN_USO', 'FINALIZADA', 'CANCELADA', 'NO_ASISTIDA'))
);

CREATE TABLE incidents (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    space_id    BIGINT NOT NULL,
    user_id     BIGINT NOT NULL,
    descripcion TEXT NOT NULL,
    estado      VARCHAR(255) NOT NULL,
    creada_en   TIMESTAMP(6) NOT NULL,
    resuelta_en TIMESTAMP(6),
    CONSTRAINT fk_incidents_space FOREIGN KEY (space_id) REFERENCES spaces (id),
    CONSTRAINT fk_incidents_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT incidents_estado_check CHECK (estado IN ('ABIERTA', 'RESUELTA'))
);

CREATE TABLE notifications (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id   BIGINT NOT NULL,
    tipo      VARCHAR(255) NOT NULL,
    mensaje   VARCHAR(500) NOT NULL,
    leida     BOOLEAN NOT NULL,
    creada_en TIMESTAMP(6) NOT NULL,
    CONSTRAINT fk_notifications_user FOREIGN KEY (user_id) REFERENCES users (id)
);

CREATE TABLE password_reset_tokens (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT NOT NULL,
    token_hash VARCHAR(64) NOT NULL,
    usado      BOOLEAN NOT NULL,
    creado_en  TIMESTAMP(6) NOT NULL,
    expira_en  TIMESTAMP(6) NOT NULL,
    CONSTRAINT password_reset_tokens_token_hash_key UNIQUE (token_hash),
    CONSTRAINT fk_password_reset_tokens_user FOREIGN KEY (user_id) REFERENCES users (id)
);

-- Una sola fila (id = 1): las reglas de reserva que configura el administrador
CREATE TABLE booking_rules (
    id                       BIGINT PRIMARY KEY,
    dias_anticipacion        INTEGER NOT NULL,
    hora_apertura            INTEGER NOT NULL,
    hora_cierre              INTEGER NOT NULL,
    horas_cancelacion        INTEGER NOT NULL,
    max_equipos_dia          INTEGER NOT NULL,
    max_horas_reserva        INTEGER NOT NULL,
    max_reservas_activas     INTEGER NOT NULL,
    max_salas_dia            INTEGER NOT NULL,
    minutos_no_asistencia    INTEGER NOT NULL,
    dominios_institucionales VARCHAR(500),
    actualizado_en           TIMESTAMP(6),
    actualizado_por          VARCHAR(255)
);

CREATE TABLE audit_log (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha          TIMESTAMP(6) NOT NULL,
    usuario_email  VARCHAR(255),
    usuario_nombre VARCHAR(150),
    usuario_rol    VARCHAR(30),
    accion         VARCHAR(40) NOT NULL,
    detalle        VARCHAR(500) NOT NULL,
    ip             VARCHAR(45)
);

CREATE INDEX idx_audit_fecha ON audit_log (fecha);
